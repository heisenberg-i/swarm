-- SWARM application schema for PostgreSQL 16 + TimescaleDB.
-- Additive only. Does NOT create, drop, truncate, or alter:
--   tenants, devices, sensor_messages, sensor_readings (hypertable)
-- swarm_pi is not owner of those tables; app columns live on sidecar tables.

CREATE TABLE tenant_profiles (
    tenant_id   UUID PRIMARY KEY REFERENCES tenants (tenant_id),
    status      VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    updated_at  TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE users (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identity_user_id   VARCHAR(36) UNIQUE,
    name               VARCHAR(255) NOT NULL,
    email              VARCHAR(255) NOT NULL UNIQUE,
    mobile             VARCHAR(20),
    password           VARCHAR(255) NOT NULL,
    role               VARCHAR(32) NOT NULL,
    status             VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    tenant_id          UUID REFERENCES tenants (tenant_id),
    created_at         TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_users_tenant ON users (tenant_id);

CREATE TABLE plants (
    plant_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_name            VARCHAR(255) NOT NULL,
    plant_type            VARCHAR(32) NOT NULL,
    location              VARCHAR(500),
    capacity              DOUBLE PRECISION,
    feedstock_type        VARCHAR(255),
    installation_date     DATE,
    status                VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    enabled_sensor_types  VARCHAR(1000),
    hmi_enabled           BOOLEAN NOT NULL DEFAULT FALSE,
    tenant_id             UUID REFERENCES tenants (tenant_id),
    created_at            TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at            TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_plants_tenant ON plants (tenant_id);

CREATE TABLE user_plants (
    user_id   BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    plant_id  BIGINT NOT NULL REFERENCES plants (plant_id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, plant_id)
);

CREATE TABLE sensor_nodes (
    node_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id           BIGINT NOT NULL REFERENCES plants (plant_id) ON DELETE CASCADE,
    node_name          VARCHAR(255) NOT NULL,
    sensor_type        VARCHAR(50) NOT NULL,
    device_chip_id     VARCHAR(32),
    device_ip          VARCHAR(45),
    firmware_version   VARCHAR(50),
    battery_level      INTEGER,
    signal_strength    INTEGER,
    status             VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    last_reading_at    TIMESTAMP,
    created_at         TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at         TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_sensor_nodes_plant ON sensor_nodes (plant_id);

CREATE TABLE user_sensor_nodes (
    user_id  BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    node_id  BIGINT NOT NULL REFERENCES sensor_nodes (node_id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, node_id)
);

CREATE TABLE device_registry (
    device_pk          BIGINT PRIMARY KEY REFERENCES devices (id),
    plant_id           BIGINT REFERENCES plants (plant_id),
    chip_id            VARCHAR(32),
    device_name        VARCHAR(128) NOT NULL,
    device_kind        VARCHAR(32) NOT NULL,
    lifecycle          VARCHAR(32) NOT NULL,
    secret_hash        VARCHAR(128),
    legacy_compat      BOOLEAN NOT NULL DEFAULT TRUE,
    last_seen_at       TIMESTAMP,
    last_ip            VARCHAR(45),
    last_rssi          INTEGER,
    firmware_version   VARCHAR(64),
    config_version     INTEGER NOT NULL DEFAULT 1,
    updated_at         TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_device_registry_plant ON device_registry (plant_id);
CREATE INDEX idx_device_registry_chip ON device_registry (chip_id);

CREATE TABLE process_areas (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id     BIGINT NOT NULL REFERENCES plants (plant_id),
    code         VARCHAR(64) NOT NULL,
    name         VARCHAR(128) NOT NULL,
    description  VARCHAR(512),
    created_at   TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_process_area_plant_code UNIQUE (plant_id, code)
);

CREATE TABLE equipment (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id         BIGINT NOT NULL REFERENCES plants (plant_id),
    process_area_id  BIGINT REFERENCES process_areas (id),
    tag              VARCHAR(64) NOT NULL,
    name             VARCHAR(128) NOT NULL,
    equipment_kind   VARCHAR(64),
    created_at       TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_equipment_plant_tag UNIQUE (plant_id, tag)
);

CREATE TABLE device_channels (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id              BIGINT NOT NULL REFERENCES devices (id),
    channel_id             TEXT NOT NULL,
    sensor_node_id         BIGINT REFERENCES sensor_nodes (node_id),
    measurement_type       VARCHAR(50) NOT NULL,
    engineering_unit       VARCHAR(32),
    instrument_tag         VARCHAR(64),
    equipment_id           BIGINT REFERENCES equipment (id),
    process_area_id        BIGINT REFERENCES process_areas (id),
    slope                  DOUBLE PRECISION NOT NULL DEFAULT 1,
    intercept              DOUBLE PRECISION NOT NULL DEFAULT 0,
    validity_min           DOUBLE PRECISION,
    validity_max           DOUBLE PRECISION,
    hard_min               DOUBLE PRECISION,
    hard_max               DOUBLE PRECISION,
    sampling_interval_sec  INTEGER,
    active                 BOOLEAN NOT NULL DEFAULT TRUE,
    created_at             TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at             TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_device_channel UNIQUE (device_id, channel_id)
);

CREATE INDEX idx_device_channels_node ON device_channels (sensor_node_id);

CREATE TABLE ingest_rejected (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_uid       VARCHAR(64),
    plant_id         BIGINT,
    transport        VARCHAR(16) NOT NULL,
    reason_code      VARCHAR(64) NOT NULL,
    reason_detail    VARCHAR(512),
    payload_excerpt  VARCHAR(1024),
    received_at      TIMESTAMP NOT NULL
);

CREATE INDEX idx_ingest_rejected_received ON ingest_rejected (received_at);

CREATE TABLE alerts (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id         BIGINT NOT NULL REFERENCES plants (plant_id),
    node_id          BIGINT,
    sensor_type      VARCHAR(50),
    title            VARCHAR(255) NOT NULL,
    message          TEXT,
    severity         VARCHAR(32) NOT NULL,
    status           VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    threshold_value  DOUBLE PRECISION,
    actual_value     DOUBLE PRECISION,
    acknowledged_by  BIGINT,
    acknowledged_at  TIMESTAMP,
    resolved_at      TIMESTAMP,
    created_at       TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_alerts_plant_status ON alerts (plant_id, status);

CREATE TABLE ai_recommendations (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id         BIGINT NOT NULL REFERENCES plants (plant_id),
    issue_type       VARCHAR(32) NOT NULL,
    recommendation   TEXT NOT NULL,
    health_score     INTEGER,
    health_status    VARCHAR(32),
    acknowledged     BOOLEAN NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE predictive_maintenance (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id                    BIGINT NOT NULL REFERENCES plants (plant_id),
    equipment_type              VARCHAR(32) NOT NULL,
    equipment_name              VARCHAR(255) NOT NULL,
    remaining_useful_life_days  INTEGER,
    sensor_type                 VARCHAR(50),
    estimated_failure_date      DATE,
    health_percentage           DOUBLE PRECISION,
    notes                       TEXT,
    created_at                  TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at                  TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE reports (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id      BIGINT REFERENCES plants (plant_id),
    report_type   VARCHAR(32) NOT NULL,
    title         VARCHAR(255) NOT NULL,
    file_path     VARCHAR(500),
    file_format   VARCHAR(10),
    generated_by  BIGINT,
    created_at    TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE system_settings (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setting_key    VARCHAR(100) NOT NULL UNIQUE,
    setting_value  TEXT,
    category       VARCHAR(50),
    description    VARCHAR(500),
    updated_at     TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE partner_organizations (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(255) NOT NULL,
    external_org_id  VARCHAR(100) NOT NULL UNIQUE,
    active           BOOLEAN NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE partner_org_plants (
    org_id    BIGINT NOT NULL REFERENCES partner_organizations (id) ON DELETE CASCADE,
    plant_id  BIGINT NOT NULL REFERENCES plants (plant_id) ON DELETE CASCADE,
    PRIMARY KEY (org_id, plant_id)
);

CREATE TABLE partner_api_keys (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id        BIGINT NOT NULL REFERENCES partner_organizations (id) ON DELETE CASCADE,
    key_hash      VARCHAR(64) NOT NULL UNIQUE,
    key_prefix    VARCHAR(16) NOT NULL,
    name          VARCHAR(255) NOT NULL,
    active        BOOLEAN NOT NULL DEFAULT TRUE,
    expires_at    TIMESTAMP,
    revoked_at    TIMESTAMP,
    last_used_at  TIMESTAMP,
    created_at    TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE hmi_equipment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id        BIGINT NOT NULL REFERENCES plants (plant_id) ON DELETE CASCADE,
    tag_no          VARCHAR(32) NOT NULL,
    name            VARCHAR(255) NOT NULL,
    zone            VARCHAR(64) NOT NULL,
    equipment_kind  VARCHAR(64) NOT NULL,
    controllable    BOOLEAN NOT NULL DEFAULT FALSE,
    sensor_node_id  BIGINT,
    sequence_order  INTEGER,
    motor_hp        DOUBLE PRECISION,
    capacity        VARCHAR(64),
    hotspot_x       DOUBLE PRECISION,
    hotspot_y       DOUBLE PRECISION,
    hotspot_w       DOUBLE PRECISION,
    hotspot_h       DOUBLE PRECISION,
    CONSTRAINT uk_hmi_equipment_plant_tag UNIQUE (plant_id, tag_no)
);

CREATE TABLE hmi_equipment_state (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id         BIGINT NOT NULL,
    equipment_id     BIGINT NOT NULL REFERENCES hmi_equipment (id) ON DELETE CASCADE,
    powered          BOOLEAN NOT NULL DEFAULT FALSE,
    running          BOOLEAN NOT NULL DEFAULT FALSE,
    mode             VARCHAR(32) NOT NULL DEFAULT 'OFF',
    last_changed_by  BIGINT,
    updated_at       TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_hmi_state_plant_equipment UNIQUE (plant_id, equipment_id)
);

CREATE TABLE hmi_plant_state (
    plant_id               BIGINT PRIMARY KEY REFERENCES plants (plant_id) ON DELETE CASCADE,
    plant_powered          BOOLEAN NOT NULL DEFAULT FALSE,
    auto_sequence_active   BOOLEAN NOT NULL DEFAULT FALSE,
    auto_sequence_step     INTEGER DEFAULT 0,
    last_changed_by        BIGINT,
    updated_at             TIMESTAMP NOT NULL DEFAULT NOW()
);

-- Empty NOVA tables so existing JPA mappings boot. NOVA source is not modified.
CREATE TABLE nova_threads (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    title            VARCHAR(255),
    sticky_plant_id  BIGINT,
    created_at       TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE nova_messages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_id   BIGINT NOT NULL REFERENCES nova_threads (id) ON DELETE CASCADE,
    role        VARCHAR(20) NOT NULL,
    content     TEXT NOT NULL,
    tools_used  VARCHAR(500),
    created_at  TIMESTAMP NOT NULL DEFAULT NOW()
);
